#!/usr/bin/env python3
"""Write the site's pages from projects.py: index.html and projects/<id>.html.

    python3 tools/build.py

Standard library only. The pages are plain HTML (GitHub Pages serves them as
they are); this script exists so every page shares one layout and one place
holds each project's facts. Edit projects.py, run it, commit both.
"""
import html
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import projects  # noqa: E402

E = html.escape


def layout(title, body, depth=0, description=""):
    up = "../" * depth
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{E(title)}</title>
<meta name="description" content="{E(description)}">
<link rel="stylesheet" href="{up}assets/style.css">
</head>
<body>
<header class="top"><div class="top-inner">
  <a class="brand" href="{up}index.html">squared-netizen</a>
  <nav><a href="{up}index.html">Main page</a><a href="{up}index.html#projects">Projects</a>
  <a href="{up}tracker.html">Sprint tracker</a>
  <a href="https://github.com/{projects.OWNER}">GitHub</a></nav>
</div></header>
<main>{body}</main>
<footer class="foot">Written from each repository's own documentation and, where it
was thin or disagreed with itself, its code. Generated by <code>tools/build.py</code>
from <code>tools/projects.py</code>.</footer>
</body>
</html>
"""


def cite(refs, key):
    keys = [r[0] for r in refs]
    return f'<sup class="ref"><a href="#ref-{key}">[{keys.index(key) + 1}]</a></sup>'


def render(text, refs):
    """[[key]] in a project's prose becomes a numbered citation."""
    out, i = [], 0
    while True:
        a = text.find("[[", i)
        if a < 0:
            out.append(text[i:])
            return "".join(out)
        b = text.index("]]", a)
        out.append(text[i:a])
        out.append(cite(refs, text[a + 2:b]))
        i = b + 2


def project_page(p):
    refs = p["refs"]
    R = lambda t: render(t, refs)  # noqa: E731
    rows = "".join(f"<tr><th>{E(k)}</th><td>{R(v)}</td></tr>" for k, v in p["infobox"])
    sections = [("Overview", None), ("Concept", None), ("Architecture", None),
                ("Features", None), ("Use cases", None), ("References", None)]
    toc = "".join(f'<li><a href="#{n.lower().replace(" ", "-")}">{n}</a></li>' for n, _ in sections)
    arch = "".join(f"<h3>{E(h)}</h3><p>{R(t)}</p>" for h, t in p["architecture"])
    feats = "".join(f"<li>{R(f)}</li>" for f in p["features"])
    uses = "".join(f"<li>{R(u)}</li>" for u in p["use_cases"])
    reflist = "".join(f'<li id="ref-{k}"><a href="{E(url)}">{E(label)}</a></li>' for k, label, url in refs)
    body = f"""<article class="article">
<h1>{E(p["name"])}</h1>
<p class="tagline">From squared-netizen's projects · <span class="status {p["status_class"]}">{E(p["status"])}</span></p>
<aside class="infobox">
  <div class="title">{E(p["name"])}</div>
  <div class="figure">{p["sketch"]}<div class="cap">{E(p["sketch_caption"])}</div></div>
  <table>{rows}</table>
</aside>
<p>{R(p["lead"])}</p>
<nav class="toc"><b>Contents</b><ol>{toc}</ol></nav>
<h2 id="overview">Overview</h2>
<p>{R(p["summary"])}</p>
<h2 id="concept">Concept</h2>
<div class="thumb">{p["concept"]}<div class="cap">{E(p["concept_caption"])}</div></div>
<h2 id="architecture">Architecture</h2>
{arch}
<h2 id="features">Features</h2>
<ul>{feats}</ul>
<h2 id="use-cases">Use cases</h2>
<ul>{uses}</ul>
<h2 id="references">References</h2>
<ol class="refs">{reflist}</ol>
</article>"""
    return layout(f'{p["name"]} - squared-netizen', body, depth=1, description=p["lead_plain"])


def index_page():
    rows = []
    for p in projects.PROJECTS:
        rows.append(
            f'<tr><td><a href="projects/{p["id"]}.html"><b>{E(p["name"])}</b></a></td>'
            f'<td>{E(p["kind"])}</td><td><span class="status {p["status_class"]}">{E(p["status"])}</span></td>'
            f'<td>{E(p["lead_plain"])}</td>'
            f'<td><a href="https://github.com/{projects.OWNER}/{p["repo"]}">source</a></td></tr>')
    planned = "".join(f"<tr><td><b>{E(n)}</b></td><td>{E(k)}</td><td>{d}</td></tr>"
                      for n, k, d in projects.PLANNED)
    other = "".join(f'<li><a href="https://github.com/{projects.OWNER}/{r}">{E(r)}</a>: {E(d)}</li>'
                    for r, d in projects.OTHER)
    body = f"""<article class="article">
<h1>squared-netizen</h1>
<p class="tagline">Projects, plans and the work in progress</p>
<aside class="infobox">
  <div class="title">squared-netizen</div>
  <div class="figure">{projects.ECOSYSTEM_SKETCH}<div class="cap">The squared projects and how they feed each other</div></div>
  <table>
    <tr><th>Works on</th><td>An Android phone, in Termux</td></tr>
    <tr><th>Languages</th><td>C++23 (modules), C, Lua 5.4, shell</td></tr>
    <tr><th>Focus</th><td>Offline-first tools; apps built on the phone, no Java, no Gradle</td></tr>
    <tr><th>Priorities</th><td>RAM, API ergonomics, speed, extensibility</td></tr>
    <tr><th>GitHub</th><td><a href="https://github.com/{projects.OWNER}">{projects.OWNER}</a></td></tr>
  </table>
</aside>
<p><b>squared-netizen</b> builds <b>squared</b>, a C++23 framework for Linux and Android, and
the tools around it: a project generator, a container format for its templates and
packages, and <b>sqterm</b>, a terminal for Android written on it. Everything is built and
tested on a phone. A clean checkout and the vendored sources build offline; the network is
a deliberate step of its own, never part of a build.</p>
<nav class="toc"><b>Contents</b><ol><li><a href="#projects">Current projects</a></li>
<li><a href="#planned">Planned projects</a></li><li><a href="#workflow">Workflow</a></li>
<li><a href="#other">Other repositories</a></li></ol></nav>
<h2 id="projects">Current projects</h2>
<div class="scroll"><table class="wikitable">
<tr><th>Project</th><th>Kind</th><th>Status</th><th>Summary</th><th>Repository</th></tr>
{"".join(rows)}
</table></div>
<h2 id="planned">Planned projects</h2>
<div class="scroll"><table class="wikitable"><tr><th>Project</th><th>Kind</th><th>Idea</th></tr>{planned}</table></div>
<h2 id="workflow">Workflow</h2>
<p>Work runs as sprints of small tasks. Each task is a pull request: a branch is pushed, GitHub
Actions builds and checks it, fixes follow until it is green, and a merge closes the task. The
<a href="tracker.html">sprint tracker</a> reads that history live from GitHub: what is in
progress, what is blocked on a red check, what is ready, and what each sprint finished.</p>
<h2 id="other">Other repositories</h2>
<ul>{other}</ul>
</article>"""
    return layout("squared-netizen", body, description="squared-netizen's projects, plans and sprint tracker")


def main():
    os.makedirs(os.path.join(ROOT, "projects"), exist_ok=True)
    with open(os.path.join(ROOT, "index.html"), "w") as f:
        f.write(index_page())
    for p in projects.PROJECTS:
        with open(os.path.join(ROOT, "projects", p["id"] + ".html"), "w") as f:
            f.write(project_page(p))
    print(f"index.html and {len(projects.PROJECTS)} project pages written")


if __name__ == "__main__":
    main()
